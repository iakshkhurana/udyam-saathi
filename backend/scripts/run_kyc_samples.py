"""Run Smart KYC on the 12 specimen applicants and write docs/kyc_results.md."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import ROOT_DIR
from app.db import SessionLocal
from app.services.kyc.ocr import BLUR_THRESHOLD, ocr_available
from app.services.kyc.service import SAMPLES, evaluate_sample
from app.utils.masking import mask_gstin, mask_name, mask_udyam
from calibrate_blur import scores, suggest

ICON = {"pass": "✅", "warn": "⚠️", "fail": "❌", "skip": "–"}
CHECK_IDS = [f"C{n:02d}" for n in range(1, 19)]


def summary_fields(r: dict) -> str:
    gst = r["docs"].get("gst_certificate", {}).get("fields", {})
    udy = r["docs"].get("udyam_certificate", {}).get("fields", {})
    sig = r["docs"].get("signatory_id", {}).get("fields", {})
    bill = r["docs"].get("address_proof", {}).get("fields", {})
    parts = [f"GSTIN {mask_gstin(gst.get('gstin')) or '—'}", f"Udyam {mask_udyam(udy.get('udyam_number')) or 'blank/—'}",
             f"Trade: {gst.get('trade_name') or '—'}", f"Signatory: {mask_name(sig.get('name'))} ({sig.get('designation') or '—'})",
             f"Bill {bill.get('bill_date') or '—'}"]
    angle = r["docs"].get("gst_certificate", {}).get("angle")
    if angle:
        parts.append(f"deskewed {angle}°")
    return "<br>".join(parts)


def cell(r: dict, cid: str) -> str:
    statuses = [c["status"] for c in r["checks"] if c["id"] == cid]
    if not statuses:
        return ""
    worst = next((s for s in ("fail", "warn", "pass", "skip") if s in statuses), "skip")
    return ICON[worst]


def main() -> list[dict]:
    if not ocr_available():
        raise SystemExit("Tesseract not available – install it first (see README)")
    with SessionLocal() as db:
        results = [evaluate_sample(db, a) for a in SAMPLES]
    caught = sum(r["flags_caught"] for r in results)
    matched = sum(r["matches"] for r in results)
    blur_rows = scores()
    lines = [
        "# Smart KYC – specimen results", "",
        f"Generated by `backend/scripts/run_kyc_samples.py` with APP_TODAY = 2026-07-15. "
        f"**Primary flag caught: {caught}/12 · final status matches the derived answer key: {matched}/12.**", "",
        "Final status: PASS → `KYC_VERIFIED`; PASS_WITH_WARNINGS → `KYC_REVIEW` (human queue); RETAKE / INCOMPLETE / "
        "FAIL → customer stays on the KYC screen with fix-it messages.", "",
        "## Summary", "",
        "| Applicant | Extracted (masked) | Final | Expected | Primary flag(s) | Caught |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        flags = ", ".join(f"{k} {v}" for k, v in r["expected_flags"].items()) or "none (clean)"
        lines.append(f"| {r['applicant']} | {summary_fields(r)} | **{r['status']}** | {r['expected_status']} | {flags} "
                     f"| {'✅' if r['flags_caught'] else '❌'} |")
    lines += ["", "## Every check", "", "| Applicant | " + " | ".join(CHECK_IDS) + " |",
              "|---|" + "---|" * len(CHECK_IDS)]
    for r in results:
        lines.append(f"| {r['applicant']} | " + " | ".join(cell(r, c) for c in CHECK_IDS) + " |")
    lines += ["", "## Problems found (customer-facing message)", ""]
    for r in results:
        problems = [c for c in r["checks"] if c["status"] in ("fail", "warn")]
        if problems:
            lines.append(f"**{r['applicant']}**")
            lines += [f"- {ICON[c['status']]} {c['id']}: {c['message_en']}" for c in problems]
            lines.append("")
    lines += ["## Blur calibration (variance of Laplacian)", "",
              f"`BLUR_THRESHOLD = {BLUR_THRESHOLD}` – midpoint between `{blur_rows[0][0]}` ({blur_rows[0][1]:.1f}) and the "
              f"next-lowest `{blur_rows[1][0]}` ({blur_rows[1][1]:.1f}); suggested {suggest(blur_rows)}.", "",
              "| Image | Score |", "|---|---|", *[f"| {n} | {s:.1f} |" for n, s in blur_rows], "",
              "Udyam *major activity* and *date of registration* differences are shown as info only (generator noise "
              "in the synthetic data)."]
    (ROOT_DIR / "docs" / "kyc_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return results


if __name__ == "__main__":
    for r in main():
        bad = [(c["id"], c["status"], c.get("doc")) for c in r["checks"] if c["status"] in ("fail", "warn")]
        print(r["applicant"], r["status"], "expected", r["expected_status"], "match" if r["matches"] else "MISMATCH", bad)
