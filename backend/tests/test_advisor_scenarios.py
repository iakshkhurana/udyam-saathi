import os

import pytest

from app.config import ROOT_DIR
from app.schemas import Profile
from app.services.catalogue import get_catalogue
from app.services.rules_engine import BASE_IDS, failed_rules, inr, recommend_bundle

CAT = get_catalogue()
RESULTS: dict[int, tuple[str, str, str]] = {}


def enabled(result):
    return {i.product_id: i for i in result.items if i.enabled}


def assert_all_eligible(result, profile):
    ids = list(enabled(result))
    assert all(not failed_rules(CAT[pid], profile, ids) for pid in ids)


def chat(client, language: str, messages: list[str]) -> dict:
    sid = client.post("/api/advisor/sessions", json={"language": language}).json()["session_id"]
    out = {}
    for m in messages:
        body = {"chip": m} if ":" in m and " " not in m else {"text": m}
        out = client.post(f"/api/advisor/sessions/{sid}/message", json=body).json()
    return out


@pytest.fixture(scope="module", autouse=True)
def write_report():
    yield
    lines = ["# Advisor test results", "",
             "Generated by `backend/tests/test_advisor_scenarios.py` (guided mode, no API key). "
             "Every scenario also re-checks that no ineligible product is returned.", "",
             "| # | Scenario | Result | Evidence |", "|---|---|---|---|"]
    for n in sorted(RESULTS):
        desc, status, evidence = RESULTS[n]
        lines.append(f"| {n} | {desc} | {status} | {evidence} |")
    passed = sum(1 for v in RESULTS.values() if v[1] == "✅ pass")
    lines += ["", f"**{passed}/{len(RESULTS)} passed in guided mode.** Scenario 6 (reply in Tamil) needs AI mode; "
              "guided mode falls back to English with a note, which is what is asserted here."]
    (ROOT_DIR / "docs" / "advisor_test_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def record(n: int, desc: str, evidence: str):
    RESULTS[n] = (desc, "✅ pass", evidence)


def test_01_tier2_asks_for_1g():
    p = Profile(segment="micro", employees=6, city_tier=2, gstin_status="Active", requested_products=["P03"])
    r = recommend_bundle(p)
    assert "P03" not in enabled(r) and any(e.product_id == "P03" and "tier" in e.rules for e in r.excluded)
    assert "P02" in enabled(r) and enabled(r)["P02"].is_base
    assert_all_eligible(r, p)
    record(1, "Tier-2 shop, 6 staff, GSTIN, asks for Biz Fibre 1G", "P03 excluded (tier 1 only) → P02 offered")


